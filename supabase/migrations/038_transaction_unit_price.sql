-- 038_transaction_unit_price.sql
-- Цена за единицу в транзакции (для выручки/маржи в отчётах).
-- nullable — старые записи и производство/брак/возврат остаются без цены.
-- Для «Арматуры» (kg_per_meter) количество хранится в метрах → цена за метр.
-- Применяется вручную в Supabase SQL Editor (общая БД staging+production).
--
-- Код переживает окно до/после применения: отчёты читают транзакции через
-- select("*") и трактуют отсутствующую/пустую цену как 0; модалка добавляет
-- unit_price в INSERT только когда цена введена. Применяйте миграцию до того,
-- как пользователи начнут вводить цены.

ALTER TABLE material_transactions
  ADD COLUMN IF NOT EXISTS unit_price numeric(14,2);

COMMENT ON COLUMN material_transactions.unit_price IS
  'Цена за единицу (тг). Для материалов с kg_per_meter — цена за метр (количество хранится в метрах). NULL = цена не указана.';
